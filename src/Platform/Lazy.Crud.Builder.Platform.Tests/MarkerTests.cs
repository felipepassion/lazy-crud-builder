using Lazy.Crud.Builder.Platform.Markers;
using Xunit;

namespace Lazy.Crud.Builder.Platform.Tests;

public class MarkerTests
{
    private static MarkerFields Fields(Ownership ownership) => new()
    {
        Aggregate = "Products", Layer = "Domain", TemplateId = "domain.command-handlers",
        Ownership = ownership, GeneratorVersion = "1.1.0", TemplateVersion = "1.1.0",
        SourceTemplate = "Domain/DomainCommandHandlers.tt",
    };

    [Fact]
    public void GeneratorOwnedHeaderStatesEditsAreOverwrittenAndWhereToCustomize()
    {
        var text = GeneratedCodeMarker.Render(Fields(Ownership.GeneratorOwned), CommentSyntax.CSharpLine)!;
        Assert.Contains("Ownership: GeneratorOwned", text);
        Assert.Contains("overwritten", text);
        Assert.Contains("Customize:", text);
        Assert.Contains("Domain/DomainCommandHandlers.tt", text);
        Assert.StartsWith("// <auto-generated>", text);
    }

    [Fact]
    public void GeneratedOnceHeaderStatesUserOwnedAndLacksOverwrittenWording()
    {
        var text = GeneratedCodeMarker.Render(Fields(Ownership.GeneratedOnce), CommentSyntax.CSharpLine)!;
        Assert.Contains("Ownership: GeneratedOnce", text);
        Assert.Contains("user-owned", text);
        Assert.Contains("will not be regenerated", text);
        Assert.DoesNotContain("overwritten", text);
    }

    [Fact]
    public void ManualIsNeverRendered()
    {
        Assert.Throws<InvalidOperationException>(() => GeneratedCodeMarker.Render(Fields(Ownership.Manual), CommentSyntax.CSharpLine));
    }

    [Fact]
    public void UnmarkableFileTypesHaveNoSyntax()
    {
        Assert.Null(CommentSyntax.ForFileName("a.json"));
        Assert.Null(CommentSyntax.ForFileName("a.xml"));
        Assert.Null(CommentSyntax.ForFileName("a.csproj"));
        Assert.Null(CommentSyntax.ForFileName("a.txt"));
        Assert.Same(CommentSyntax.CSharpLine, CommentSyntax.ForFileName("A.cs"));
        Assert.Same(CommentSyntax.Razor, CommentSyntax.ForFileName("Index.razor"));
        Assert.Same(CommentSyntax.CBlock, CommentSyntax.ForFileName("Index.razor.css"));
        Assert.Same(CommentSyntax.Batch, CommentSyntax.ForFileName("Migrations.generated.bat"));
        Assert.Same(CommentSyntax.T4, CommentSyntax.ForFileName("DefaultEntities.tt"));
    }

    [Theory]
    [InlineData("GeneratorOwned")]
    [InlineData("GeneratedOnce")]
    public void RoundTripsThroughEverySyntax(string ownershipName)
    {
        OwnershipNames.TryParse(ownershipName, out var ownership);
        foreach (var syntax in CommentSyntax.All)
        {
            var marker = GeneratedCodeMarker.Render(Fields(ownership), syntax)!;
            var content = marker + "body line 1\r\nbody line 2\r\n";
            Assert.True(GeneratedCodeMarker.TryParse(content, out var info), syntax.Id);
            Assert.True(info!.IsV2, syntax.Id);
            Assert.Empty(info.Problems);
            Assert.Equal("Products", info.Get("Aggregate"));
            Assert.Equal("Domain", info.Get("Layer"));
            Assert.Equal("domain.command-handlers", info.Get("TemplateId"));
            Assert.Equal(ownership, info.Ownership);
            Assert.Equal("1.1.0", info.Get("GeneratorVersion"));
            Assert.Equal("1.1.0", info.Get("TemplateVersion"));
            Assert.Equal(MarkerFields.GeneratorIdentity, info.Get("Generator"));
            Assert.Equal("body line 1\r\nbody line 2\r\n", content.Substring(info.Block!.BodyStart));
        }
    }

    [Fact]
    public void ParsesOnlyTheOpeningLinesWithoutReadingTheRest()
    {
        var marker = GeneratedCodeMarker.Render(Fields(Ownership.GeneratorOwned), CommentSyntax.CSharpLine)!;
        var content = marker + "// Ownership: GeneratedOnce (a trap in the body)\r\n" + new string('x', 5000);
        Assert.True(GeneratedCodeMarker.TryParse(content, out var info));
        Assert.Equal(Ownership.GeneratorOwned, info!.Ownership);
    }

    [Fact]
    public void RecognizesHistoricalV1TestHeader()
    {
        var v1 = "// <auto-generated>\r\n//     This code was generated by a T4 template (Tests.Domain.tt).\r\n//     Changes to this file will be lost when the code is regenerated.\r\n//     DO NOT EDIT this file manually.\r\n// </auto-generated>\r\n/// <summary>Auto-generated by LazyCrud. DO NOT EDIT.</summary>\r\nusing Xunit;\r\n";
        Assert.True(GeneratedCodeMarker.TryParse(v1, out var info));
        Assert.True(info!.IsV1);
        Assert.False(info.IsV2);
        Assert.StartsWith("/// <summary>", v1.Substring(info.Block!.BodyStart));
    }

    [Fact]
    public void ForeignAutoGeneratedBlockIsNotALazyCrudMarker()
    {
        var foreign = "// <auto-generated>\r\n// Generated by SomeOtherTool.\r\n// </auto-generated>\r\nclass A {}\r\n";
        Assert.True(GeneratedCodeMarker.TryParse(foreign, out var info));
        Assert.Equal("foreign", info!.Version);
    }

    [Fact]
    public void FileWithoutMarkerHasNoBlock()
    {
        Assert.False(GeneratedCodeMarker.TryFindMarkerBlock("using System;\r\n// <auto-generated>\r\n", out _));
        Assert.False(GeneratedCodeMarker.TryParse("class A {}", out _));
    }

    [Fact]
    public void ByteOrderMarkBeforeMarkerIsTolerated()
    {
        var marker = GeneratedCodeMarker.Render(Fields(Ownership.GeneratorOwned), CommentSyntax.CSharpLine)!;
        Assert.True(GeneratedCodeMarker.TryParse("﻿" + marker + "body", out var info));
        Assert.True(info!.IsV2);
        Assert.Equal("body", ("﻿" + marker + "body").Substring(info.Block!.BodyStart));
    }

    [Fact]
    public void MalformedV2MarkerReportsProblems()
    {
        var text = "// <auto-generated>\r\n// LazyCrud-Marker: v2\r\n// Ownership: Bogus\r\n// </auto-generated>\r\nbody";
        Assert.True(GeneratedCodeMarker.TryParse(text, out var info));
        Assert.True(info!.IsV2);
        Assert.NotEmpty(info.Problems);
        Assert.Null(info.Ownership);
    }
}
